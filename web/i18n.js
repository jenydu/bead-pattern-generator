let lang = "en";

function t(key, vars) {
  const s = I18N[lang][key] ?? I18N.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`)) : s;
}

// Fill every element tagged data-i18n="key" (text) or data-i18n-attr="attribute:key;...".
function applyStatic() {
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.title = t("title");
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-attr]")) {
    for (const pair of el.dataset.i18nAttr.split(";")) {
      const [attr, key] = pair.split(":");
      el.setAttribute(attr, t(key));
    }
  }
}

function initLang() {
  let saved = null;
  try { saved = localStorage.getItem("lang"); } catch (e) { /* storage blocked: use the browser language */ }
  lang = saved === "zh" || saved === "en" ? saved
    : (navigator.language || "").toLowerCase().startsWith("zh") ? "zh" : "en";
}
function setLang(l) {
  lang = l;
  try { localStorage.setItem("lang", l); } catch (e) { /* not remembered, still works */ }
  applyStatic();
}
